"""Generate the keyword matcher's Dart tables from pinned Unicode data."""

import argparse
import hashlib
from pathlib import Path

SOURCE_15_1 = "https://www.unicode.org/Public/15.1.0/ucd/CaseFolding.txt"
SOURCE_16_0 = "https://www.unicode.org/Public/16.0.0/ucd/CaseFolding.txt"
SHA256_15_1 = "4e55acfdc32825a22e87670e9056a3bf94ad7c5400065778e9e10f8314372bcf"
SHA256_16_0 = "6f1f9c588eb4a5c718d9e8f93b782685e5c7fec872cf05e8e6878053599e09bb"
HEADER = f"""// Generated by tool/generate_unicode_case_folding.py.
// Sources:
// {SOURCE_15_1}
// {SOURCE_16_0}
// Copyright © 2023–2024 Unicode, Inc.
// Data license: doc/development/unicode-data-license.txt (Unicode-3.0).

part of 'unicode_simple_case_folding.dart';
"""


def read_mappings(path: Path, sha256: str) -> dict[int, int]:
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != sha256:
        raise ValueError(f"{path} does not match the pinned Unicode data file")
    mappings = {}
    for line in data.decode("utf-8").splitlines():
        row = line.partition("#")[0].strip()
        if not row:
            continue
        source, status, target, _ = (part.strip() for part in row.split(";"))
        if status in {"C", "S"}:
            code_point = int(source, 16)
            if code_point >= 0x80:
                mappings[code_point] = int(target, 16)
    return mappings


def format_table(name: str, mappings: dict[int, int]) -> str:
    lines = [
        f"  0x{source:x}: 0x{target:x},\n"
        for source, target in sorted(mappings.items())
    ]
    return f"\nconst {name} = <int, int>{{\n" + "".join(lines) + "};\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("unicode_15_1", type=Path, help=f"Local copy of {SOURCE_15_1}")
    parser.add_argument("unicode_16_0", type=Path, help=f"Local copy of {SOURCE_16_0}")
    args = parser.parse_args()
    try:
        base = read_mappings(args.unicode_15_1, SHA256_15_1)
        newer = read_mappings(args.unicode_16_0, SHA256_16_0)
    except (OSError, ValueError) as error:
        parser.error(str(error))
    if any(newer.get(source) != target for source, target in base.items()):
        parser.error("Unicode 16.0 must preserve the Unicode 15.1 mappings")
    additions = {source: target for source, target in newer.items() if source not in base}

    root = Path(__file__).resolve().parents[1]
    output = root / "lib/foundation/unicode_simple_case_folding_data.dart"
    generated = (
        HEADER
        + format_table("_simpleFolds", base)
        + format_table("_unicode16Additions", additions)
    )
    output.write_text(generated, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
